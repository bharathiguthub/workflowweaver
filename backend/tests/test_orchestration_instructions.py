def test_instructions_only_sse_sequence():
    body = plan(instruction=LOYALTY).json()
    service, _ = make_service()
    runner = ExecutionRunner(service, EventBroker(), max_workers=1)
    try:
        channel, future = runner.start(execution_request(body))
        future.result(timeout=10)
    finally:
        runner.shutdown()
    types = [e.event_type.value for e in channel.events()]
    assert types[:2] == ["approval_verified", "workflow_started"]
    assert types.count("resource_verified") == 6 and types[-1] == "workflow_completed"
    teams = [e for e in channel.events() if e.event_type.value == "step_succeeded"][-1]
    assert teams.metadata["integration"] == "teams" and teams.step_number == 7


