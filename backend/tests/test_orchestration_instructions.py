def test_input_digest_changes_with_any_input():
    base = input_digest("instructions_only", None, LOYALTY, 5)
    assert base != input_digest("instructions_only", None, LOYALTY + " ", 5)
    assert base != input_digest("instructions_only", None, LOYALTY, 4)
    assert base != input_digest("document_and_instructions", None, LOYALTY, 5)
    steps = [{"step_number": 1, "integration": "notion", "action": "create_page", "arguments": {"title": "t"},
              "depends_on": []}]
    assert plan_digest(steps, TARGET, base) != plan_digest(steps, TARGET, input_digest("instructions_only", None,
                                                                                         FOCUS, 5))


def test_approval_from_another_plan_is_rejected():
    first = plan(instruction=LOYALTY).json()
    second = plan(instruction=LOYALTY.replace("Loyalty App", "Points App")).json()
    service, _ = make_service()
    response = service.execute(execution_request(first, digest=second["plan_digest"]))
    assert [e.code for e in response.errors] == ["APPROVAL_PLAN_MISMATCH"] and service.registry.store.calls == []


def test_changed_inputs_after_planning_invalidate_the_approval():
    """If the recorded inputs differ (e.g. the plan was regenerated from other instructions under
    the same id), the executor's recomputed digest no longer matches the approval."""
    body = plan(instruction=LOYALTY).json()
    registry = get_plan_registry()
    registry.record(body["workflow_id"], TARGET, None, None, body["plan_digest"],
                    input_digest=input_digest("instructions_only", None, FOCUS, 5))
    service, _ = make_service()
    response = service.execute(execution_request(body))
    assert [e.code for e in response.errors] == ["APPROVAL_PLAN_MISMATCH"]


def test_plain_digest_without_inputs_is_not_accepted():
    body = plan(instruction=LOYALTY).json()
    steps = [{k: s[k] for k in ("step_number", "integration", "action", "arguments", "depends_on")}
             for s in body["planned_steps"]]
    service, _ = make_service()
    response = service.execute(execution_request(body, digest=plan_digest(steps, TARGET)))
    assert [e.code for e in response.errors] == ["APPROVAL_PLAN_MISMATCH"]


