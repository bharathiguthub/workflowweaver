"""Phase 7.2 enhancement: natural-language workflow instructions.

Three input modes on POST /api/v1/workflows/orchestration/plan:
    instructions_only           Gemini/Groq generate the plan; no Google Drive step
    document_only               unchanged (regression: tests/test_orchestration.py)
    document_and_instructions   the document is the only factual source; instructions shape it

Instructions can never change the compiled plan's structure, integrations or destinations;
invalid instructions are rejected before any AI call; approval is bound to the plan digest,
which includes the input digest. All external clients are fakes; nothing is written.
"""

