"""Google Drive Sandbox Test (Phase 6.1): a deterministic, Drive-only plan for the UI.

POST /api/v1/workflows/drive-sandbox/plan   body {"mode": "mock"|"dry_run"|"real", "project"?: ProjectPlanDraft}
    200  PLANNED  exactly three steps, built deterministically by the SERVER. No LLM is ever
                  called (Groq, Gemini and PLANNER_MODE play no part), so the smoke test works
                  even when every AI provider is down:
                    1 google_drive.create_folder    unique run folder inside the sandbox folder
                    2 google_drive.create_document  the Markdown project report inside it,
                      verified after upload (parent, size, md5)
                    3 google_drive.read_document    read the report back (read-only) and verify
                      its content: it must hash to content_sha256 (SHA-256 of the report)
                  Nothing is executed and nothing is written to Google Drive while planning.
    409           mode exceeds the server's INTEGRATION_MODE
    422           the supplied project produced a report that failed the plan validator
    503           execution disabled, or the Drive sandbox is not configured for that mode

``project`` is the structured plan returned by the AI Project Plan workflow (Gemini/Groq/
Claude). It is rendered to markdown by the server and goes through the same validator as
every plan (unsafe content, length), so AI output cannot change the steps, the tools, or the
destination - only the report text. Execution happens only through the normal approval-gated
/executions endpoints, which re-validate the plan and apply every real-mode gate.
"""

import hashlib
from datetime import datetime, timezone
from typing import Literal
from uuid import uuid4

from fastapi import APIRouter, HTTPException, status
from fastapi.responses import JSONResponse
from pydantic import BaseModel, ConfigDict

from app.agents.execution.modes import allowed_modes
from app.agents.plan_registry import get_plan_registry
from app.agents.project_workflow import ProjectPlanDraft
from app.agents.validation import validate_draft
from app.core.config import IntegrationMode, get_settings
from app.integrations.config import load_integration_config
from app.integrations.errors import IntegrationConfigError
from app.integrations.readiness import drive_sandbox_issues, real_drive_issues
from app.schemas.execution import ExecutionMode
from app.schemas.plan import (
    DraftPlan,
    DraftStep,
    IntegrationTarget,
    PlanResponse,
    PlanStatus,
    StepArgument,
    ValidationResult,
)

router = APIRouter(prefix="/api/v1/workflows/drive-sandbox", tags=["drive-sandbox"])

PLANNER_NAME = "drive-sandbox"


class DrivePlanRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    mode: ExecutionMode
    project: ProjectPlanDraft | None = None
    # Google Drive-only workflow: any other integration target is rejected (422).
    target: Literal["google_drive"] | None = None


class DriveSandboxPlanResponse(PlanResponse):
    mode: ExecutionMode
    integration: Literal["google_drive"] = "google_drive"
    destination_alias: str | None  # sandbox folder alias (dry_run/real); never the folder id
    operation: str
    rollback: str
    real_write: bool
    report_title: str
    report_bytes: int


def _unavailable(detail: str) -> HTTPException:
    return HTTPException(status.HTTP_503_SERVICE_UNAVAILABLE, detail)


def render_project_report(project: ProjectPlanDraft | None, *, workflow_id: str, stamp: str) -> str:
    """Markdown report. Synthetic content when no project is given."""
    if project is None:
        return "\n".join([
            "# WorkflowWeaver sandbox report",
            "",
            f"Synthetic report uploaded by the Google Drive Sandbox Test ({stamp}).",
            f"Workflow {workflow_id}. It contains no real data and can be deleted.",
        ]) + "\n"
    lines = [f"# {project.project_title}", "", "## Overview", "", project.overview, "", "## Action items", ""]
    for i, item in enumerate(project.action_items, start=1):
        lines += [f"### {i}. {item.title}", "", item.description, "",
                  f"- Suggested priority: {item.priority}", f"- Suggested owner: {item.owner}", ""]
    lines += ["---", f"Generated by WorkflowWeaver ({stamp}, workflow {workflow_id}). "
                     "Owners are suggested teams, not assignments; no deadlines were set."]
    return "\n".join(lines) + "\n"


@router.post("/plan", response_model=DriveSandboxPlanResponse)
def plan_drive_sandbox(payload: DrivePlanRequest) -> JSONResponse:
    settings = get_settings()
    mode = IntegrationMode(payload.mode)
    if mode not in allowed_modes(settings.integration_mode):
        raise HTTPException(status.HTTP_409_CONFLICT,
                            f"This server allows modes up to '{settings.integration_mode.value}'.")
    if not settings.mock_execution_enabled:
        raise _unavailable("Execution is disabled (MOCK_EXECUTION_ENABLED=false).")

    folder: str | None = None
    if mode is not IntegrationMode.MOCK:
        try:
            config = load_integration_config(settings)
        except IntegrationConfigError as exc:
            raise _unavailable(str(exc)) from exc
        issues = real_drive_issues(settings, config) if mode is IntegrationMode.REAL \
            else drive_sandbox_issues(settings, config)
        if issues:
            raise _unavailable(" ".join(issues))
        folder = settings.smoke_test_drive_folder

    workflow_id = uuid4()
    now = datetime.now(timezone.utc)
    stamp = now.strftime("%Y-%m-%d %H:%M:%S UTC")
    run_id = str(workflow_id)[:8]  # unique per plan, even for two plans in the same second
    folder_name = f"WorkflowWeaver run {now.strftime('%Y-%m-%d %H%M%S')} {run_id}"
    base = (payload.project.project_title if payload.project else "Sandbox report")[:120]
    report_title = f"{base} - report {now.strftime('%Y-%m-%d %H%M%S')} {run_id}.md"
    report = render_project_report(payload.project, workflow_id=str(workflow_id), stamp=stamp)
    report_sha256 = hashlib.sha256(report.encode("utf-8")).hexdigest()

    folder_args = [StepArgument(name="name", value=folder_name)]
    if folder:
        folder_args.append(StepArgument(name="folder", value=folder))
    draft = DraftPlan(
        summary="Google Drive Sandbox Test: create a run folder in the sandbox, upload the project report into it "
                "(verified after upload) and read the report back to verify its content.",
        steps=[
            DraftStep(step_number=1, integration="google_drive", action="create_folder",
                      description="Create a run folder inside the Google Drive sandbox folder",
                      arguments=folder_args, depends_on=[]),
            DraftStep(step_number=2, integration="google_drive", action="create_document",
                      description="Upload the project report into the run folder and verify it",
                      arguments=[StepArgument(name="title", value=report_title),
                                 StepArgument(name="content", value=report),
                                 StepArgument(name="parent_step", value="1")], depends_on=[1]),
            DraftStep(step_number=3, integration="google_drive", action="read_document",
                      description="Read the uploaded report back and verify its content (read-only)",
                      arguments=[StepArgument(name="document_name", value=report_title),
                                 StepArgument(name="parent_step", value="1"),
                                 StepArgument(name="content_sha256", value=report_sha256)], depends_on=[1, 2]),
        ],
    )
    plan, issues = validate_draft(draft, max_steps=max(settings.max_workflow_steps, len(draft.steps)))
    operation, rollback = {
        IntegrationMode.MOCK: ("In-memory mock folder + report + verified read-back (no network)",
                               "Mock compensation (in memory)"),
        IntegrationMode.DRY_RUN: ("Build the Drive folder, upload and read-back requests without sending them",
                                  "Offline only; nothing is sent"),
        IntegrationMode.REAL: (f"Drive REST API (drive.file scope): create a run folder in sandbox folder '{folder}', "
                               "upload the report (multipart) and verify it, then read the report back and verify "
                               "its content",
                               "If a step fails, the report and run folder created by this run are moved to Drive "
                               "trash (newest first). A successful run keeps them."),
    }[mode]
    common = dict(integration_target=IntegrationTarget.GOOGLE_DRIVE, workflow_id=workflow_id, planner=PLANNER_NAME, summary=draft.summary, errors=[],
                  planning_attempts=1, mode=mode.value, destination_alias=folder, operation=operation,
                  rollback=rollback, report_title=report_title, report_bytes=len(report.encode("utf-8")))
    if plan is None:
        response = DriveSandboxPlanResponse(status=PlanStatus.INVALID, planned_steps=[],
                                            validation=ValidationResult(is_valid=False, issues=issues),
                                            real_write=False, **common)
        return JSONResponse(status_code=422, content=response.model_dump(mode="json"))
    get_plan_registry().record(workflow_id, IntegrationTarget.GOOGLE_DRIVE.value)
    response = DriveSandboxPlanResponse(status=PlanStatus.PLANNED, planned_steps=plan.steps,
                                        validation=ValidationResult(is_valid=True, issues=[]),
                                        real_write=mode is IntegrationMode.REAL, **common)
    return JSONResponse(status_code=200, content=response.model_dump(mode="json"))

