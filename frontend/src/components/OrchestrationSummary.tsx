import {
  actionLabel,
  integrationLabel,
  type ExtractedItem,
  type OrchestrationInputMode,
  type OrchestrationPlanResponse,
  type Provenance,
} from "../api/types";
import { Badge } from "./StatusBadge";

const SECTIONS = [
  ["objectives", "Objectives"],
  ["technical_tasks", "Technical tasks"],
  ["deliverables", "Deliverables"],
  ["acceptance_criteria", "Acceptance criteria"],
] as const;

const STAGE_LABELS = {
  instructions_check: "Instructions check",
  source_validation: "Source validation",
  document_read: "Document read",
  extraction: "AI extraction",
  plan_validation: "Plan validation",
} as const;

const STAGE_TONE = { passed: "success", failed: "danger", simulated: "warning", skipped: "neutral" } as const;

export const INPUT_MODE_LABELS: Record<OrchestrationInputMode, string> = {
  document_only: "Google Drive document only",
  instructions_only: "Instructions only (AI-generated plan, no source document)",
  document_and_instructions: "Google Drive document + instructions (the document is the factual source)",
};

const PROVENANCE_LABEL: Record<Exclude<Provenance, "none">, string> = {
  document: "from source",
  instructions: "from your instructions",
  suggested: "AI suggestion, not in source",
};

function provenance(label: string, value: string, source: Provenance) {
  if (source === "none") return `${label}: not stated`;
  return `${label}: ${value} (${PROVENANCE_LABEL[source]})`;
}

const ORIGIN_NOTE: Record<ExtractedItem["origin"], string | null> = {
  document: null,
  generated: null, // every item of an instructions-only plan is AI-generated (said once, above)
  instructions: "(from your instructions)",
  unverified: "(not found in source)",
};

/** Phase 7.2: everything the reviewer approves for the [Drive ->] Notion -> Teams workflow. */
export function OrchestrationSummary({ plan }: { plan: OrchestrationPlanResponse }) {
  const steps = plan.planned_steps;
  const project = steps.find((s) => s.integration === "notion" && !s.arguments.parent_step);
  const children = steps.filter((s) => s.integration === "notion" && s.arguments.parent_step);
  return (
    <div className="mt-3 space-y-3 text-sm">
      <p className="text-xs text-slate-700">
        Input: <strong>{INPUT_MODE_LABELS[plan.input_mode]}</strong>
      </p>

      {plan.source ? (
        <div className="rounded-lg bg-slate-50 p-3">
          <h3 className="font-medium text-slate-900">Source document (Google Drive, read-only)</h3>
          <dl className="mt-1 grid grid-cols-[7rem_1fr] gap-x-2 gap-y-0.5 text-xs">
            <dt className="text-slate-500">Name</dt>
            <dd className="text-slate-800">{plan.source.name}</dd>
            <dt className="text-slate-500">File ID</dt>
            <dd className="break-all font-mono text-slate-800">{plan.source.file_id}</dd>
            <dt className="text-slate-500">SHA-256</dt>
            <dd className="break-all font-mono text-slate-800">{plan.source.sha256}</dd>
            <dt className="text-slate-500">Folder</dt>
            <dd className="font-mono text-slate-800">{plan.destinations.drive_folder ?? "(unknown)"}</dd>
          </dl>
          <p className="mt-1 text-xs text-slate-600">
            {plan.source.simulated
              ? "Simulated: a synthetic fixture (this mode never contacts Google Drive)."
              : "Verified inside the approved sandbox folder and app-accessible. Execution re-reads it and stops if its content changed."}
          </p>
        </div>
      ) : (
        <div className="rounded-lg border border-amber-200 bg-amber-50 p-3 text-xs text-amber-900">
          No source document: Google Drive is not used. The phases, objectives, tasks, deliverables and criteria below were
          generated by AI from your instructions; they are not facts from any document. Review them before approving.
        </div>
      )}

      {plan.instructions && (
        <div className="rounded-lg bg-slate-50 p-3">
          <h3 className="font-medium text-slate-900">Your instructions</h3>
          <p className="mt-1 whitespace-pre-wrap break-words text-xs text-slate-800">{plan.instructions}</p>
          <p className="mt-1 text-xs text-slate-600">
            {plan.source
              ? "Used only to decide how to process the document (selection, order, wording); never as a source of facts."
              : "Used as the brief for the AI-generated plan."}{" "}
            Instructions cannot change the integrations, destinations or approval rules.
          </p>
        </div>
      )}

      {plan.instruction_notes.length > 0 && (
        <div className="rounded-lg border border-amber-200 bg-amber-50 p-3 text-amber-900">
          <p className="font-medium">Not applied from your instructions:</p>
          <ul aria-label="Instructions not applied" className="mt-1 list-disc pl-5 text-xs">
            {plan.instruction_notes.map((n) => (
              <li key={n}>{n}</li>
            ))}
          </ul>
        </div>
      )}

      <div>
        <h3 className="font-medium text-slate-900">Planning stages</h3>
        <ol aria-label="Planning stages" className="mt-1 space-y-1">
          {plan.stages.map((s) => (
            <li key={s.stage} className="flex flex-wrap items-center gap-2">
              <Badge tone={STAGE_TONE[s.status]} label={s.status} />
              <span className="font-medium text-slate-800">{STAGE_LABELS[s.stage]}</span>
              <span className="text-xs text-slate-600">{s.detail}</span>
            </li>
          ))}
        </ol>
      </div>

      <div className="grid gap-3 sm:grid-cols-2">
        <div>
          <h3 className="font-medium text-slate-900">Checks performed</h3>
          <ul aria-label="Checks performed" className="mt-1 list-disc pl-5 text-xs text-slate-700">
            {plan.checks.performed.map((c) => (
              <li key={c}>{c}</li>
            ))}
          </ul>
        </div>
        <div>
          <h3 className="font-medium text-slate-900">Simulated (not performed)</h3>
          {plan.checks.simulated.length === 0 ? (
            <p className="mt-1 text-xs text-slate-700">Nothing: every step runs against the real services after approval.</p>
          ) : (
            <ul aria-label="Simulated steps" className="mt-1 list-disc pl-5 text-xs text-slate-700">
              {plan.checks.simulated.map((c) => (
                <li key={c}>{c}</li>
              ))}
            </ul>
          )}
        </div>
      </div>

      {plan.warnings.length > 0 && (
        <div className="rounded-lg border border-amber-200 bg-amber-50 p-3 text-amber-900">
          <p className="font-medium">Review these notes:</p>
          <ul aria-label="Extraction warnings" className="mt-1 list-disc pl-5 text-xs">
            {plan.warnings.map((w) => (
              <li key={w}>{w}</li>
            ))}
          </ul>
        </div>
      )}

      {plan.extraction && (
        <div>
          <h3 className="font-medium text-slate-900">
            {plan.source ? "Extracted from the source" : "Generated plan"}: {plan.extraction.project_title} (
            {plan.extraction.phases.length} phase(s))
          </h3>
          <p className="mt-1 text-xs text-slate-700">
            {plan.extraction.summary}
            {plan.extraction.summary_source === "source_text" && (
              <>
                {" "}
                <span className="font-medium text-sky-800">(copied from the source document)</span>
              </>
            )}
          </p>
          <ol aria-label="Extracted phases" className="mt-2 space-y-2">
            {plan.extraction.phases.map((p, i) => (
              <li key={p.title} className="rounded-md border border-slate-200 p-2">
                <p className="font-medium text-slate-900">
                  Phase {i + 1}: {p.title}
                </p>
                {p.summary ? (
                  <p className="mt-0.5 text-xs text-slate-800" aria-label={`Phase ${i + 1} summary`}>
                    {p.summary}
                    {p.summary_source === "source_text" && (
                      <>
                        {" "}
                        <span className="font-medium text-sky-800">(copied from the source document)</span>
                      </>
                    )}
                  </p>
                ) : null}
                <p className="text-xs text-slate-600">
                  {provenance("Priority", p.priority, p.priority_source)} · {provenance("Owner", p.owner, p.owner_source)}
                </p>
                <div className="mt-1 grid gap-2 sm:grid-cols-2">
                  {SECTIONS.map(([key, label]) => (
                    <div key={key}>
                      <p className="text-xs font-medium text-slate-700">{label}</p>
                      {p.sections[key].length === 0 ? (
                        <p className="text-xs text-slate-500">Not stated.</p>
                      ) : (
                        <ul className="list-disc pl-4 text-xs text-slate-800">
                          {p.sections[key].map((item) => (
                            <li key={item.text}>
                              {item.text}
                              {ORIGIN_NOTE[item.origin] && (
                                <span className={`ml-1 font-medium ${item.origin === "unverified" ? "text-amber-800" : "text-sky-800"}`}>
                                  {ORIGIN_NOTE[item.origin]}
                                </span>
                              )}
                            </li>
                          ))}
                        </ul>
                      )}
                    </div>
                  ))}
                </div>
              </li>
            ))}
          </ol>
        </div>
      )}

      {project && (
        <div className="rounded-lg bg-slate-50 p-3">
          <h3 className="font-medium text-slate-900">Notion pages</h3>
          <ul aria-label="Notion pages" className="mt-1 text-xs text-slate-800">
            <li>
              Step {project.step_number} · <strong>{project.arguments.title}</strong> under sandbox parent{" "}
              <span className="font-mono">{plan.destinations.notion_parent ?? "(mock)"}</span>
              <ul className="mt-0.5 list-disc pl-6">
                {children.map((c) => (
                  <li key={c.step_number}>
                    Step {c.step_number} · {c.arguments.title} (child of step {c.arguments.parent_step})
                  </li>
                ))}
              </ul>
            </li>
          </ul>
          <p className="mt-1 text-xs text-slate-600">
            Each page is read back after creation. If a Notion step fails, only the pages this run created are moved to trash and
            Teams is not notified.
          </p>
        </div>
      )}

      <div>
        <h3 className="font-medium text-slate-900">Step dependencies</h3>
        <ol aria-label="Step dependencies" className="mt-1 space-y-0.5 text-xs text-slate-800">
          {steps.map((s) => (
            <li key={s.step_number}>
              Step {s.step_number} · {integrationLabel(s.integration)} {actionLabel(s.action).toLowerCase()}
              {s.depends_on.length > 0 ? ` ← after step(s) ${s.depends_on.join(", ")}` : " (first)"}
            </li>
          ))}
        </ol>
      </div>

      <p className="text-xs text-slate-700">
        Writes after approval: <strong>{plan.write_summary.notion_pages}</strong> Notion page(s),{" "}
        <strong>{plan.write_summary.teams_messages}</strong> Teams message(s), {plan.write_summary.drive_writes} Google Drive
        write(s){plan.source ? " (the source is only read)" : ""}. Plan digest{" "}
        <span className="font-mono">{plan.plan_digest?.slice(0, 16) ?? "-"}</span>… binds your approval to exactly this plan and its
        inputs (input digest <span className="font-mono">{plan.input_digest.slice(0, 12)}</span>…).
      </p>
    </div>
  );
}
