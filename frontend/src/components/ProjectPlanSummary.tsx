import { aiPlannerLabel, type ProjectPlanResponse } from "../api/types";
import { Badge } from "./StatusBadge";

const PRIORITY_TONE = { High: "danger", Medium: "warning", Low: "neutral" } as const;

/** The AI-proposed project, as reviewed before approval. */
export function ProjectPlanSummary({ plan }: { plan: ProjectPlanResponse }) {
  const project = plan.project;
  return (
    <div className="mt-3 space-y-3" aria-label="Proposed project">
      <div className="flex flex-wrap gap-2">
        {plan.ai_generated ? (
          <Badge
            tone="violet"
            label={`AI-generated by ${aiPlannerLabel(plan.planner) ?? plan.planner}${plan.model ? ` · ${plan.model}` : ""}`}
          />
        ) : (
          <Badge tone="warning" label="Mock planner (not AI)" />
        )}
        {plan.ai_generated && plan.fallback_used && (
          <Badge tone="warning" label={`Fallback planner used (${aiPlannerLabel(plan.primary_planner) ?? "primary"} unavailable)`} />
        )}
        {plan.status === "PLANNED" && <Badge tone="neutral" label={`${plan.page_count} Notion page(s) on approval`} />}
      </div>
      {project && (
        <>
          <div>
            <h3 className="text-sm font-semibold text-slate-900">{project.project_title}</h3>
            <p className="mt-1 text-sm text-slate-700">{project.overview}</p>
          </div>
          <div className="overflow-x-auto">
            <table className="min-w-full text-left text-sm">
              <caption className="sr-only">Proposed action items</caption>
              <thead className="border-b border-slate-200 text-xs uppercase text-slate-500">
                <tr>
                  <th scope="col" className="py-2 pr-3">#</th>
                  <th scope="col" className="py-2 pr-3">Action item</th>
                  <th scope="col" className="py-2 pr-3">Priority</th>
                  <th scope="col" className="py-2">Suggested owner</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100">
                {project.action_items.map((item, i) => (
                  <tr key={`${item.title}-${i}`} className="align-top">
                    <td className="py-2 pr-3 font-mono text-xs">{i + 1}</td>
                    <td className="py-2 pr-3">
                      <span className="font-medium text-slate-900">{item.title}</span>
                      <span className="mt-0.5 block text-xs text-slate-600">{item.description}</span>
                    </td>
                    <td className="py-2 pr-3">
                      <Badge tone={PRIORITY_TONE[item.priority] ?? "neutral"} label={item.priority} />
                    </td>
                    <td className="py-2 text-slate-800">{item.owner}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <p className="text-xs text-slate-500">Owners are suggested teams, not assignments. No deadlines are set.</p>
        </>
      )}
    </div>
  );
}
