function instructionsSteps(real: boolean): WorkflowStep[] {
  const project: WorkflowStep = { step_number: 1, integration: "notion", action: "create_page", description: "Create the project page",
    arguments: { title: "Loyalty App", content: "Generated by AI", ...(real ? { parent: "engineering" } : {}) }, depends_on: [] };
  const children: WorkflowStep[] = PHASES.map((p, i) => ({ step_number: i + 2, integration: "notion", action: "create_page",
    description: `Create phase ${i + 1}`, arguments: { title: `Phase ${i + 1}: ${p}`, content: "Objectives:\n- x", parent_step: "1" }, depends_on: [1] }));
  const teams: WorkflowStep = { step_number: 7, integration: "teams", action: "send_message", description: "Notify Teams",
    arguments: { message: "WorkflowWeaver: orchestration\nProject: Loyalty App\nSource: AI-generated from workflow instructions",
      link_step: "1", ...(real ? { channel: "sandbox" } : {}) }, depends_on: [1, 2, 3, 4, 5, 6] };
  return [project, ...children, teams];
}

