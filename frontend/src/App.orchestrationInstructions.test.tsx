function documentInstructionsPlan(): OrchestrationPlanResponse {
  const base = instructionsPlan("mock");
  const read: WorkflowStep = { step_number: 1, integration: "google_drive", action: "read_document", description: "Read the approved source",
    arguments: { document_name: NAME, folder: "sandbox", file_id: SOURCE_ID, expected_sha256: "ef".repeat(32) }, depends_on: [] };
  const shifted = base.planned_steps.map((s) => ({
    ...s, step_number: s.step_number + 1,
    depends_on: s.step_number === 1 ? [1] : s.depends_on.map((d) => d + 1),
    arguments: { ...s.arguments, ...(s.arguments.parent_step ? { parent_step: "2" } : {}), ...(s.arguments.link_step ? { link_step: "2" } : {}) },
  }));
  return {
    ...base, input_mode: "document_and_instructions", instructions: FOCUS, instruction_notes: [],
    source: { file_id: SOURCE_ID, name: NAME, mime_type: "text/markdown", size_bytes: 2844, modified_time: null, sha256: "ef".repeat(32), simulated: true },
    destinations: { ...base.destinations, drive_folder: "sandbox" },
    planned_steps: [read, ...shifted],
    extraction: base.extraction && {
      ...base.extraction,
      phases: base.extraction.phases.map((p, i) => ({
        ...p,
        sections: {
          ...p.sections,
          objectives: [{ text: `Objective ${i}`, in_source: true, origin: "document" }],
          technical_tasks: i === 0 ? [{ text: "Pair every task with a security review", in_source: false, origin: "instructions" }] : [],
        },
        owner: i === 1 ? "Growth team" : "", owner_source: i === 1 ? "instructions" : "none",
      })),
    },
  };
}

