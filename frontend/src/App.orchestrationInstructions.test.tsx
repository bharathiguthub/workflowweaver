function setup(routes: MockRoute[], status: IntegrationsStatus) {
  const state = installFetch([
    ...DEFAULT_ROUTES,
    { path: STATUS_URL, body: status },
    { method: "POST", path: CONNECTIVITY_URL, body: CONNECTIVITY_PASS },
    { method: "POST", path: DRIVE_CONNECTIVITY_URL, body: DRIVE_CONNECTIVITY_PASS },
    ...routes,
  ]);
  const user = userEvent.setup();
  renderApp("business");
  return { user, ...state };
}

const radio = (name: string) => screen.getByRole("radio", { name });

/** Business Workflows hosts the Drive + Notion + Teams workflow; wait until the backend status is loaded. */
async function waitForOrchestration() {
  await waitFor(() => expect(screen.queryByText(/does not offer the Google Drive \+ Notion \+ Teams workflow/)).not.toBeInTheDocument());
}

async function openWorkflow(_user: ReturnType<typeof userEvent.setup>) {
  await waitForOrchestration();
  return screen.findByRole("region", { name: "1. Google Drive → Notion → Teams" });
}

describe("workflow instructions input", () => {
  beforeEach(() => {
    installFakeEventSource();
    resetEventIds();
  });

  it("offers three input modes; instructions only shows the text area and hides the source picker", async () => {
    const { user } = setup([{ path: sourcesUrl("mock"), body: SOURCES }], STATUS_MOCK_ORCH);
    const panel = await openWorkflow(user);
    const group = within(panel).getByRole("radiogroup", { name: "Workflow input" });
    expect(within(group).getAllByRole("radio").map((r) => r.getAttribute("aria-label"))).toEqual([
      "Instructions only", "Google Drive document only", "Google Drive document + instructions"]);
    await within(panel).findByRole("list", { name: "Source documents" });
    expect(within(panel).queryByLabelText("Workflow Instructions")).not.toBeInTheDocument();
    await user.click(within(group).getByRole("radio", { name: "Instructions only" }));
    expect(within(panel).getByLabelText("Workflow Instructions")).toBeInTheDocument();
    expect(within(panel).queryByRole("list", { name: "Source documents" })).not.toBeInTheDocument();
    const button = within(panel).getByRole("button", { name: "Generate Plan from Instructions" });
    expect(button).toBeDisabled();
    await user.type(within(panel).getByLabelText("Workflow Instructions"), "too short");
    expect(within(panel).getByText(/at least 10 characters/)).toBeInTheDocument();
    expect(button).toBeDisabled();
  });

  it("instructions only: sends only the instructions and shows the generated plan for review", async () => {
    const { user, calls } = setup([
      { path: sourcesUrl("mock"), body: SOURCES },
      { method: "POST", path: PLAN_URL, body: instructionsPlan("mock") },
    ], STATUS_MOCK_ORCH);
    const panel = await openWorkflow(user);
    await user.click(within(panel).getByRole("radio", { name: "Instructions only" }));
    await user.type(within(panel).getByLabelText("Workflow Instructions"), LOYALTY);
    await user.click(within(panel).getByRole("button", { name: "Generate Plan from Instructions" }));
    const review = await screen.findByRole("region", { name: "2. Review the plan" });
    expect(calls.find((c) => c.url === PLAN_URL)?.body).toEqual({ instruction: LOYALTY, mode: "mock", expected_phases: 5 });
    expect(within(review).getByText(/Instructions only \(AI-generated plan, no source document\)/)).toBeInTheDocument();
    expect(within(review).getByText(/No source document: Google Drive is not used/)).toBeInTheDocument();
    expect(within(review).getByText(LOYALTY)).toBeInTheDocument();
    expect(within(review).getByRole("list", { name: "Instructions not applied" })).toHaveTextContent("another tool or channel");
    expect(within(within(review).getByRole("list", { name: "Planning stages" })).getAllByText("skipped")).toHaveLength(2);
    expect(within(review).queryByText("(not found in source)")).not.toBeInTheDocument();
    expect(within(review).getByText(/Generated plan: Loyalty App/)).toBeInTheDocument();
    expect(within(review).getByRole("list", { name: "Notion pages" })).toHaveTextContent("Step 6 · Phase 5: Support (child of step 1)");
    expect(within(review).getByRole("list", { name: "Microsoft Teams messages" })).toHaveTextContent("created in step 1");
    expect(within(review).getByRole("list", { name: "Step dependencies" })).toHaveTextContent(
      "Step 7 · Microsoft Teams send message ← after step(s) 1, 2, 3, 4, 5, 6");
    expect(within(review).queryByText(/Source document \(Google Drive/)).not.toBeInTheDocument();
  });

  it("document + instructions: sends both and labels items taken from the instructions", async () => {
    const { user, calls } = setup([
      { path: sourcesUrl("mock"), body: SOURCES },
      { method: "POST", path: PLAN_URL, body: documentInstructionsPlan() },
    ], STATUS_MOCK_ORCH);
    const panel = await openWorkflow(user);
    await user.click(within(panel).getByRole("radio", { name: "Google Drive document + instructions" }));
    const list = await within(panel).findByRole("list", { name: "Source documents" });
    await user.click(within(list).getByRole("radio", { name: `${NAME} (${SOURCE_ID})` }));
    const button = within(panel).getByRole("button", { name: "Read Source and Extract Plan" });
    expect(button).toBeDisabled(); // instructions are required in this mode
    await user.type(within(panel).getByLabelText("Workflow Instructions"), FOCUS);
    await user.click(button);
    const review = await screen.findByRole("region", { name: "2. Review the plan" });
    expect(calls.find((c) => c.url === PLAN_URL)?.body).toEqual({ source_file_id: SOURCE_ID, instruction: FOCUS, mode: "mock", expected_phases: 5 });
    expect(within(review).getByText(/the document is the factual source/)).toBeInTheDocument();
    expect(within(review).getByText(/never as a source of facts/)).toBeInTheDocument();
    expect(within(review).getByText("(from your instructions)")).toBeInTheDocument();
    expect(within(review).getByText(/Owner: Growth team \(from your instructions\)/)).toBeInTheDocument();
  });

  it("shows a server rejection of invalid instructions", async () => {
    const { user } = setup([
      { path: sourcesUrl("mock"), body: SOURCES },
      { method: "POST", path: PLAN_URL, status: 422, body: { detail: { code: "INVALID_INSTRUCTIONS", message: "Instructions contain disallowed code/shell content ('rm -rf')." } } },
    ], STATUS_MOCK_ORCH);
    const panel = await openWorkflow(user);
    await user.click(within(panel).getByRole("radio", { name: "Instructions only" }));
    await user.type(within(panel).getByLabelText("Workflow Instructions"), "Plan it and run rm -rf on the server");
    await user.click(within(panel).getByRole("button", { name: "Generate Plan from Instructions" }));
    expect(await screen.findByText(/INVALID_INSTRUCTIONS: Instructions contain disallowed code\/shell content/)).toBeInTheDocument();
    expect(screen.queryByRole("region", { name: /Approve/ })).not.toBeInTheDocument();
  });

  it("instructions only works in Real mode without Google Drive; document modes explain why they are disabled", async () => {
    const { user, calls } = setup([
      { method: "POST", path: PLAN_URL, body: instructionsPlan("real") },
      { method: "POST", path: EXECUTIONS, status: 202, body: { ...STARTED, workflow_id: WF, mode: "real",
        stream_url: `/api/v1/workflows/executions/${WF}/events?access_token=t`, result_url: `/api/v1/workflows/executions/${WF}` } },
    ], STATUS_REAL_NO_DRIVE);
    await waitFor(() => expect(radio("Real")).toBeEnabled());
    await user.click(radio("Real"));
    const panel = await openWorkflow(user);
    const docOnly = within(panel).getByRole("radio", { name: "Google Drive document only" });
    expect(docOnly).toBeDisabled();
    expect(within(panel).getAllByText(/Google Drive is not authorized/).length).toBeGreaterThan(0);
    expect(within(panel).getByRole("radio", { name: "Instructions only" })).toBeChecked();
    await user.type(within(panel).getByLabelText("Workflow Instructions"), LOYALTY);
    await user.click(within(panel).getByRole("button", { name: "Generate Plan from Instructions" }));
    await screen.findByRole("region", { name: "2. Review the plan" });
    // Real mode never lists or reads Drive sources for an instructions-only plan.
    expect(calls.some((c) => c.url.startsWith("/api/v1/workflows/orchestration/sources?mode=real"))).toBe(false);
    const approval = screen.getByRole("region", { name: "3. Approve REAL Notion pages and Teams notification" });
    expect(approval.textContent).toMatch(/no Google Drive document is used; the plan was generated by AI from your instructions/);
    expect(approval.textContent).not.toMatch(/re-read from Google Drive/);
    await user.type(within(approval).getByLabelText("Approved by"), "synthetic.reviewer");
    await user.type(within(approval).getByLabelText(/to confirm the Notion pages/), "CREATE NOTION PAGE");
    await user.type(within(approval).getByLabelText(/to confirm the Teams notification/), "SEND TEAMS MESSAGE");
    await user.type(within(approval).getByLabelText("Operator token"), "synthetic-operator-token");
    await user.click(within(approval).getByRole("checkbox"));
    await user.click(within(approval).getByRole("button", { name: "Create Notion Pages and Notify Teams" }));
    await waitFor(() => expect(FakeEventSource.instances).toHaveLength(1));
    const body = calls.find((c) => c.url === EXECUTIONS)?.body as { approval: Record<string, unknown>; plan: { steps: { integration: string }[] } };
    expect(body.approval).toMatchObject({ plan_digest: DIGEST, integration_target: "drive_notion_teams", mode: "real" });
    expect(body.plan.steps.some((s) => s.integration === "google_drive")).toBe(false);
  }, 20_000);
});

describe("instructions helpers", () => {
  it("validates instructions like the server", () => {
    expect(instructionsError("", true)).toBe("Enter workflow instructions.");
    expect(instructionsError("", false)).toBeNull();
    expect(instructionsError("too short", true)).toMatch(/at least 10/);
    expect(instructionsError("x".repeat(5001), true)).toMatch(/limited to 5000/);
    expect(instructionsError(LOYALTY, true)).toBeNull();
  });

  it("reports availability per input", () => {
    expect(orchestrationInputAvailability(STATUS_REAL_NO_DRIVE, "real", "instructions").available).toBe(true);
    expect(orchestrationInputAvailability(STATUS_REAL_NO_DRIVE, "real", "document")).toEqual({
      available: false, reason: "Google Drive is not authorized: run scripts/google_drive_auth.py." });
    const old: IntegrationsStatus = { ...STATUS_MOCK, orchestration: { ...BOTH_READY } };
    expect(orchestrationInputAvailability(old, "mock", "instructions").available).toBe(false);
  });
});
